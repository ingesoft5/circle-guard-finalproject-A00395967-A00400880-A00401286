package com.circleguard.promotion.service;

import com.circleguard.promotion.model.graph.CircleNode;
import com.circleguard.promotion.repository.graph.CircleNodeRepository;
import com.circleguard.promotion.repository.graph.UserNodeRepository;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class AutoCircleServiceTest {

    @Mock
    private UserNodeRepository userRepository;
    @Mock
    private CircleNodeRepository circleRepository;
    @Mock
    private CircleService circleService;

    @InjectMocks
    private AutoCircleService autoCircleService;

    @Test
    void evaluateEncounter_sameUser_doesNothing() {
        autoCircleService.evaluateEncounter("u1", "u1");

        verifyNoInteractions(userRepository, circleRepository, circleService);
    }

    @Test
    void evaluateEncounter_nullUser_doesNothing() {
        autoCircleService.evaluateEncounter(null, "u2");

        verifyNoInteractions(userRepository, circleRepository, circleService);
    }

    @Test
    void evaluateEncounter_durationBelowThreshold_doesNotCreateCircle() {
        when(userRepository.getCumulativeEncounterDuration("u1", "u2")).thenReturn(3599L);

        autoCircleService.evaluateEncounter("u1", "u2");

        verify(circleRepository, never()).save(any());
        verifyNoInteractions(circleService);
    }

    @Test
    void evaluateEncounter_noEncounterData_doesNotCreateCircle() {
        when(userRepository.getCumulativeEncounterDuration("u1", "u2")).thenReturn(null);

        autoCircleService.evaluateEncounter("u1", "u2");

        verify(circleRepository, never()).save(any());
    }

    @Test
    void evaluateEncounter_thresholdReachedAndNotConnected_createsAutoCircleAndJoinsBoth() {
        when(userRepository.getCumulativeEncounterDuration("u1", "u2")).thenReturn(3600L);
        when(circleRepository.findCommonCircles("u1", "u2"))
                .thenReturn(List.of(CircleNode.builder().isAutoGenerated(false).build()));

        autoCircleService.evaluateEncounter("u1", "u2");

        ArgumentCaptor<CircleNode> captor = ArgumentCaptor.forClass(CircleNode.class);
        verify(circleRepository).save(captor.capture());
        CircleNode created = captor.getValue();
        assertThat(created.getIsAutoGenerated()).isTrue();
        assertThat(created.getIsActive()).isTrue();
        assertThat(created.getName()).startsWith("Auto Mesh ");
        assertThat(created.getInviteCode()).matches("AUTO-[0-9A-F]{8}");
        verify(circleService).joinCircle("u1", created.getInviteCode());
        verify(circleService).joinCircle("u2", created.getInviteCode());
    }

    @Test
    void evaluateEncounter_alreadyInAutoCircle_doesNotCreateAnother() {
        when(userRepository.getCumulativeEncounterDuration("u1", "u2")).thenReturn(7200L);
        when(circleRepository.findCommonCircles("u1", "u2"))
                .thenReturn(List.of(CircleNode.builder().isAutoGenerated(true).build()));

        autoCircleService.evaluateEncounter("u1", "u2");

        verify(circleRepository, never()).save(any());
        verifyNoInteractions(circleService);
    }
}
